"""FAA Airport Capacity Profiles (PDF, 2014-2019): hourly capacity rate ranges per weather condition, extracted
once into config/capacity_profiles.yaml. The measured cross-check for the TAF annual service volume."""

from __future__ import annotations

import re
from pathlib import Path

import yaml
from pydantic import BaseModel, Field
from pypdf import PdfReader

from app.config import CONFIG_DIR

CONDITIONS = ("visual", "marginal", "instrument")
# Variants seen 2014-2019: "rate range in Visual conditions for 28/01 Side-Byes is currently 104-107 operations per
# hour", "... in South flow Visual conditions is cu rrently 172-173 ...", "... for East Flow operations in Visual
# conditions is 97-115 ...", "... in Marginal conditions is ~61 ...", "116 - 125", "59 – 77", "Low Instrument".
RANGE = re.compile(
    r"capacity rate(?: range)?(?P<before>[^.]{0,80}?)\b(?:low\s+)?(?P<cond>visual|marginal|instrument) conditions"
    r"(?P<after>[^.]{0,80}?)(?:is|are)\s*(?:cu\s?rrently\s*)?~?\s*(?P<lo>\d{2,3})(?:\s*[-–]\s*(?P<hi>\d{2,3}))?"
    r"\s*operations per hour",
    re.IGNORECASE,
)
LOW_INSTRUMENT = re.compile(r"low\s+instrument conditions", re.IGNORECASE)
FILE_NAME = re.compile(r"^(?P<airport>[A-Z]{3})-Airport-Capacity-Profile(?:-Appendix-A)?-(?P<year>\d{4})\.pdf$")


class ConditionRates(BaseModel):
    configuration: str
    low: int
    high: int

    @property
    def midpoint(self) -> float:
        return (self.low + self.high) / 2


class ProfileRates(BaseModel):
    airport: str
    year: int
    url: str
    visual: list[ConditionRates] = Field(default_factory=list)
    marginal: list[ConditionRates] = Field(default_factory=list)
    instrument: list[ConditionRates] = Field(default_factory=list)

    def primary(self, condition: str) -> ConditionRates | None:
        """The first configuration listed per condition is the profile's primary one."""
        rates: list[ConditionRates] = getattr(self, condition)
        return rates[0] if rates else None


class ProfilesFile(BaseModel):
    version: str
    generated: str
    source: str
    profiles: list[ProfileRates]

    def by_airport(self) -> dict[str, ProfileRates]:
        return {p.airport: p for p in self.profiles}


def pdf_text(path: Path) -> str:
    return re.sub(r"\s+", " ", " ".join((page.extract_text() or "") for page in PdfReader(str(path)).pages))


def parse_rates(text: str, airport: str, year: int, url: str) -> ProfileRates:
    """Pull every 'capacity rate range in <condition> ... A-B operations per hour' sentence out of a profile's text."""
    out = ProfileRates(airport=airport, year=year, url=url)
    for m in RANGE.finditer(text):
        cond = m.group("cond").lower()
        config = " ".join((m.group("before") + " " + m.group("after")).split()).strip(" .,") or "primary"
        config = re.sub(r"^(?:(?:in|for|the)\s+)+|\s+(?:is|are)$", "", config).strip() or "primary"
        if LOW_INSTRUMENT.search(m.group(0)):
            config = f"low instrument: {config}"
        lo = int(m.group("lo"))
        hi = int(m.group("hi")) if m.group("hi") else lo
        rates: list[ConditionRates] = getattr(out, cond)
        entry = ConditionRates(configuration=config, low=min(lo, hi), high=max(lo, hi))
        if config.startswith("low instrument"):
            rates.append(entry)  # never the primary instrument rate
        else:
            rates.insert(sum(1 for r in rates if not r.configuration.startswith("low instrument")), entry)
    return out


def extract_dir(profiles_dir: Path, base_url: str) -> list[ProfileRates]:
    out: list[ProfileRates] = []
    for pdf in sorted(profiles_dir.glob("*.pdf")):
        m = FILE_NAME.match(pdf.name)
        if not m or pdf.stat().st_size < 10_000:
            continue
        rates = parse_rates(pdf_text(pdf), m.group("airport"), int(m.group("year")), f"{base_url}/{pdf.name}")
        if rates.visual or rates.marginal or rates.instrument:
            out.append(rates)
    return out


def load_profiles(path: Path = CONFIG_DIR / "capacity_profiles.yaml") -> ProfilesFile | None:
    if not path.exists():
        return None
    return ProfilesFile.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))


def dump_profiles(data: ProfilesFile, path: Path = CONFIG_DIR / "capacity_profiles.yaml") -> None:
    head = ("# GENERATED by `agent profiles` from the FAA Airport Capacity Profile PDFs (hourly operations per weather\n"
            "# condition; the first configuration per condition is the primary one). Do not edit by hand.\n")
    path.write_text(head + yaml.safe_dump(data.model_dump(), sort_keys=False, width=120), encoding="utf-8", newline="\n")
